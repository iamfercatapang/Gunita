import { useEffect, useRef, useSyncExternalStore } from 'react';

import { type CapturesSnapshot, getCaptures, subscribeCaptures } from '../../state/captures';

export function useCaptures(): CapturesSnapshot {
  return useSyncExternalStore(subscribeCaptures, getCaptures);
}

/** Run `onEscape` when Escape is pressed while mounted. */
export function useEscape(onEscape: () => void): void {
  useEffect(() => {
    const onKey = (e: KeyboardEvent): void => {
      if (e.key === 'Escape') onEscape();
    };
    document.addEventListener('keydown', onKey);
    return () => document.removeEventListener('keydown', onKey);
  }, [onEscape]);
}

/**
 * A muted video showing one frame as a thumbnail. Safari shows nothing for
 * preload="metadata" until the video seeks, so nudge it a little way in.
 */
export function VideoThumb({ src }: { src: string }) {
  const ref = useRef<HTMLVideoElement>(null);
  useEffect(() => {
    const video = ref.current;
    if (!video) return;
    const seek = (): void => {
      video.currentTime = Math.min(0.5, (video.duration || 0) * 0.1);
    };
    video.addEventListener('loadedmetadata', seek, { once: true });
    return () => video.removeEventListener('loadedmetadata', seek);
  }, []);
  return <video ref={ref} src={src} preload="metadata" muted playsInline />;
}

